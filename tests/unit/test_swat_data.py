def _write_csv_with_columns(tmp_path: Path, columns: dict, filename: str = "fix1.csv") -> Path:
    """Write a minimal synthetic CSV with the given column dict, adding a Timestamp."""
    n = 5
    start = pd.Timestamp("2015-12-22 16:00:00", tz="UTC")
    ts = [start + pd.Timedelta(seconds=i) for i in range(n)]
    ts_str = [t.strftime("%d/%m/%Y %I:%M:%S %p") for t in ts]
    data = {"Timestamp": ts_str}
    data.update({k: v if len(v) == n else [v[0]] * n for k, v in columns.items()})
    df = pd.DataFrame(data)
    p = tmp_path / filename
    df.to_csv(p, index=False)
    return p


class TestLabelColumnLeakagePrevention:
    """Fix 1: label_col parameter and multi-candidate guard."""

    def test_single_label_col_auto_detected_and_removed(self, tmp_path):
        """One recognized label column is auto-detected and excluded from features."""
        p = _write_csv_with_columns(tmp_path, {
            "FIT101": [2.0] * 5,
            "LIT101": [500.0] * 5,
            "Normal/Attack": ["Normal", "Normal", "Attack", "Attack", "Normal"],
        })
        features, labels = load_swat_dataframe(p)
        assert labels is not None
        assert "Normal/Attack" not in features.columns
        assert len(labels) == 5
        # Verify features are numeric
        for col in features.columns:
            assert np.issubdtype(features[col].dtype, np.number)

    def test_two_label_cols_no_explicit_selection_raises(self, tmp_path):
        """Two recognized label columns with no explicit selection must raise ValueError."""
        p = _write_csv_with_columns(tmp_path, {
            "FIT101": [2.0] * 5,
            "Normal/Attack": ["Normal"] * 5,
            "Label": ["Normal"] * 5,
        })
        with pytest.raises(ValueError, match="Multiple recognized label column candidates"):
            load_swat_dataframe(p)

    def test_two_label_cols_explicit_selection_removes_only_selected(self, tmp_path):
        """With explicit label_col, only the named column is extracted.
        The unselected recognized candidate column triggers a ValueError (leakage guard).
        """
        p = _write_csv_with_columns(tmp_path, {
            "FIT101": [2.0] * 5,
            "Normal/Attack": ["Normal"] * 5,
            "Label": ["Normal"] * 5,
        })
        # With two candidates, explicit selection of one must raise because
        # the other candidate remains and could silently leak.
        with pytest.raises(ValueError, match="additional recognized label column"):
            load_swat_dataframe(p, label_col="Normal/Attack")

    def test_explicit_nonexistent_label_col_raises(self, tmp_path):
        """Explicitly requesting a label column that does not exist must raise ValueError."""
        p = _write_csv_with_columns(tmp_path, {
            "FIT101": [2.0] * 5,
            "Normal/Attack": ["Normal"] * 5,
        })
        with pytest.raises(ValueError, match="not found"):
            load_swat_dataframe(p, label_col="NonExistentColumn")

    def test_no_label_col_in_csv_returns_none(self, tmp_path):
        """CSV with no recognized label columns returns labels=None."""
        p = _write_csv_with_columns(tmp_path, {
            "FIT101": [2.0] * 5,
            "LIT101": [500.0] * 5,
        })
        features, labels = load_swat_dataframe(p)
        assert labels is None
        assert len(features) == 5

    def test_explicit_label_col_correct_selection_succeeds(self, tmp_path):
        """Explicit label_col on a CSV with exactly that one recognized column works."""
        p = _write_csv_with_columns(tmp_path, {
            "FIT101": [2.0] * 5,
            "Normal/Attack": ["Attack", "Normal", "Normal", "Attack", "Normal"],
        })
        features, labels = load_swat_dataframe(p, label_col="Normal/Attack")
        assert labels is not None
        assert list(labels) == ["Attack", "Normal", "Normal", "Attack", "Normal"]
        assert "Normal/Attack" not in features.columns

    def test_numeric_feature_validation_still_applies_after_label_removal(self, tmp_path):
        """After label column removal, non-numeric feature columns still raise ValueError."""
        n = 5
        start = pd.Timestamp("2015-12-22 16:00:00", tz="UTC")
        ts = [start + pd.Timedelta(seconds=i) for i in range(n)]
        data = {
            "Timestamp": [t.strftime("%d/%m/%Y %I:%M:%S %p") for t in ts],
            "FIT101": [2.0, "bad_value", 2.1, 2.2, 2.3],
            "Normal/Attack": ["Normal"] * n,
        }
        p = tmp_path / "bad_feature.csv"
        pd.DataFrame(data).to_csv(p, index=False)
        with pytest.raises(ValueError, match="contains non-numeric values"):
            load_swat_dataframe(p)


