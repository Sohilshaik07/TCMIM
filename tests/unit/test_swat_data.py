class TestFilterStageByTagType:
    """Fix 4: filter_stage_by_tag_type filters by SWaTTagType, not by Modality."""

    def _make_mixed_stage_df(self) -> pd.DataFrame:
        """Return a small DataFrame mixing sensors and actuators from Stage 5."""
        return pd.DataFrame({
            "PIT501": [1.5, 1.6],   # SENSOR, Modality.PRESSURE
            "FIT501": [3.0, 3.1],   # SENSOR, Modality.UNKNOWN
            "P501":   [1.0, 1.0],   # ACTUATOR, Modality.DIGITAL_STATE
            "MV501":  [2.0, 2.0],   # ACTUATOR, Modality.DIGITAL_STATE
        })

    def test_filter_sensors_returns_only_sensors(self):
        """Filtering SENSOR type returns PIT501 and FIT501, not P501 or MV501."""
        df = self._make_mixed_stage_df()
        sensor_df = filter_stage_by_tag_type(df, SWaTTagType.SENSOR)
        assert set(sensor_df.columns) == {"PIT501", "FIT501"}
        assert "P501" not in sensor_df.columns
        assert "MV501" not in sensor_df.columns

    def test_filter_actuators_returns_only_actuators(self):
        """Filtering ACTUATOR type returns P501 and MV501, not PIT501 or FIT501."""
        df = self._make_mixed_stage_df()
        actuator_df = filter_stage_by_tag_type(df, SWaTTagType.ACTUATOR)
        assert set(actuator_df.columns) == {"P501", "MV501"}
        assert "PIT501" not in actuator_df.columns
        assert "FIT501" not in actuator_df.columns

    def test_filter_returns_copy_not_view(self):
        """Result must be a copy; mutating it must not affect original."""
        df = self._make_mixed_stage_df()
        sensor_df = filter_stage_by_tag_type(df, SWaTTagType.SENSOR)
        sensor_df["PIT501"] = 99.0
        assert df["PIT501"].iloc[0] != 99.0

    def test_filter_preserves_column_order(self):
        """Column order from the original DataFrame must be preserved."""
        df = pd.DataFrame({
            "FIT501": [3.0],
            "PIT501": [1.5],
        })
        sensor_df = filter_stage_by_tag_type(df, SWaTTagType.SENSOR)
        assert list(sensor_df.columns) == ["FIT501", "PIT501"]

    def test_filter_unknown_type_returns_only_unknown_tagged_cols(self):
        """Filtering UNKNOWN type returns columns not in the registry with no prefix match."""
        df = pd.DataFrame({
            "FIT501": [3.0],
            "UNRECOGNIZED_XYZ": [0.0],
        })
        unknown_df = filter_stage_by_tag_type(df, SWaTTagType.UNKNOWN)
        assert "UNRECOGNIZED_XYZ" in unknown_df.columns
        assert "FIT501" not in unknown_df.columns

    def test_filter_empty_result_returns_empty_dataframe(self):
        """Filtering for ACTUATOR on a sensor-only DataFrame returns empty DataFrame."""
        df = pd.DataFrame({"FIT501": [3.0], "PIT501": [1.5]})
        result = filter_stage_by_tag_type(df, SWaTTagType.ACTUATOR)
        assert result.empty
        assert list(result.columns) == []

    def test_tag_type_does_not_conflate_with_modality(self):
        """PIT501 (Modality.PRESSURE) and FIT501 (Modality.UNKNOWN) are both SENSOR type.
        Filtering by SENSOR must include both regardless of Modality differences."""
        df = self._make_mixed_stage_df()
        sensor_df = filter_stage_by_tag_type(df, SWaTTagType.SENSOR)
        # Both a PRESSURE-modality sensor and an UNKNOWN-modality sensor must appear
        assert "PIT501" in sensor_df.columns  # Modality.PRESSURE
        assert "FIT501" in sensor_df.columns  # Modality.UNKNOWN
        # Their modalities differ, but tag type is SENSOR for both
        pit_info = parse_swat_tag("PIT501")
        fit_info = parse_swat_tag("FIT501")
        assert pit_info.tag_type == fit_info.tag_type == SWaTTagType.SENSOR
        assert pit_info.modality != fit_info.modality
