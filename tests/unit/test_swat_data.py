class TestSamplingFrequencyInference:
    def test_regular_1hz_synthetic_data(self):
        idx = pd.date_range("2015-12-22", periods=10, freq="1s", tz="UTC")
        freq = infer_sampling_frequency(idx)
        assert pytest.approx(freq, abs=1e-5) == 1.0

    def test_regular_0_1hz_synthetic_data(self):
        idx = pd.date_range("2015-12-22", periods=10, freq="10s", tz="UTC")
        freq = infer_sampling_frequency(idx)
        assert pytest.approx(freq, abs=1e-5) == 0.1

    def test_insufficient_data_raises_error(self):
        idx_single = pd.date_range("2015-12-22", periods=1, freq="1s", tz="UTC")
        with pytest.raises(ValueError, match="Insufficient data"):
            infer_sampling_frequency(idx_single)

    def test_duplicate_timestamps_detected_and_rejected(self):
        idx = pd.DatetimeIndex([
            pd.Timestamp("2015-12-22 10:00:00", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:00", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:01", tz="UTC"),
        ])
        with pytest.raises(ValueError, match="duplicate timestamp"):
            infer_sampling_frequency(idx)

    def test_out_of_order_timestamps_rejected(self):
        idx = pd.DatetimeIndex([
            pd.Timestamp("2015-12-22 10:00:02", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:01", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:03", tz="UTC"),
        ])
        with pytest.raises(ValueError, match="non-monotonic"):
            infer_sampling_frequency(idx)

    def test_gaps_rejected_in_strict_mode(self):
        # 1s, 1s, then a 10s gap, then 1s
        idx = pd.DatetimeIndex([
            pd.Timestamp("2015-12-22 10:00:00", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:01", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:02", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:12", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:13", tz="UTC"),
        ])
        with pytest.raises(ValueError, match="gap"):
            infer_sampling_frequency(idx, allow_gaps=False)

    def test_gaps_allowed_when_flagged(self):
        idx = pd.DatetimeIndex([
            pd.Timestamp("2015-12-22 10:00:00", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:01", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:02", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:12", tz="UTC"),
            pd.Timestamp("2015-12-22 10:00:13", tz="UTC"),
        ])
        # With allow_gaps=True, median delta is 1s -> 1.0 Hz
        freq = infer_sampling_frequency(idx, allow_gaps=True)
        assert pytest.approx(freq, abs=1e-5) == 1.0

    def test_analyze_sampling_continuity_report(self):
        idx = pd.date_range("2015-12-22", periods=5, freq="1s", tz="UTC")
        report = analyze_sampling_continuity(idx)
        assert report.total_timestamps == 5
        assert report.median_interval_s == 1.0
        assert report.min_interval_s == 1.0
        assert report.max_interval_s == 1.0
        assert report.duplicate_count == 0
        assert report.gap_count == 0
        assert report.is_strictly_uniform is True
        assert report.inferred_frequency_hz == 1.0


