def _create_synthetic_swat_csv(
    tmp_path: Path,
    n_rows: int = 10,
    time_format: str = "%d/%m/%Y %I:%M:%S %p",
    include_label: bool = True,
    leading_trailing_whitespace: bool = True,
    dt_seconds: float = 1.0,
    inject_duplicate: bool = False,
    inject_out_of_order: bool = False,
    inject_non_numeric_feature: bool = False,
) -> Path:
    """Generate a strictly synthetic SWaT CSV fixture in a temporary file."""
    start = pd.Timestamp("2015-12-22 16:00:00", tz="UTC")
    ts_list = [start + pd.Timedelta(seconds=i * dt_seconds) for i in range(n_rows)]

    if inject_duplicate and n_rows >= 2:
        ts_list[1] = ts_list[0]

    if inject_out_of_order and n_rows >= 3:
        ts_list[1], ts_list[2] = ts_list[2], ts_list[1]

    ts_strings = [ts.strftime(time_format) for ts in ts_list]

    data = {
        " Timestamp ": ts_strings if leading_trailing_whitespace else ts_strings,
        " FIT101 ": np.linspace(2.0, 2.5, n_rows),
        " LIT101 ": np.linspace(500.0, 520.0, n_rows),
        " MV101 ": [1.0 if i % 2 == 0 else 2.0 for i in range(n_rows)],
        " P101 ": [1.0] * n_rows,
        " AIT201 ": np.linspace(150.0, 160.0, n_rows),
        " DPIT301 ": np.linspace(10.0, 12.0, n_rows),
        " P401 ": [2.0] * n_rows,
        " PIT501 ": np.linspace(1.5, 2.0, n_rows),
        " LIT601 ": np.linspace(800.0, 810.0, n_rows),
    }

    if not leading_trailing_whitespace:
        data = {k.strip(): v for k, v in data.items()}

    if inject_non_numeric_feature:
        fit_col = list(data[" FIT101 "])
        fit_col[0] = "corrupted_text"
        data[" FIT101 "] = fit_col

    if include_label:
        label_col = " Normal/Attack " if leading_trailing_whitespace else "Normal/Attack"
        data[label_col] = [
            "Normal" if i < n_rows // 2 else "Attack" for i in range(n_rows)
        ]

    df = pd.DataFrame(data)
    csv_file = tmp_path / "synthetic_swat_fixture.csv"
    df.to_csv(csv_file, index=False)
    return csv_file


