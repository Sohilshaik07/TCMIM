class TestSWaTTagClassification:
    def test_all_registered_tags_have_valid_types(self):
        for tag, info in SWAT_TAG_REGISTRY.items():
            assert info.tag == tag
            assert info.tag_type in (SWaTTagType.SENSOR, SWaTTagType.ACTUATOR)
            assert info.stage in list(SWaTProcessStage)
            assert isinstance(info.modality, Modality)

    def test_verified_stages_p1_to_p6(self):
        # Stage 1
        assert SWAT_STAGE_MAP["FIT101"] == SWaTProcessStage.P1
        assert SWAT_STAGE_MAP["MV101"] == SWaTProcessStage.P1
        # Stage 2
        assert SWAT_STAGE_MAP["AIT201"] == SWaTProcessStage.P2
        assert SWAT_STAGE_MAP["P201"] == SWaTProcessStage.P2
        # Stage 3
        assert SWAT_STAGE_MAP["DPIT301"] == SWaTProcessStage.P3
        assert SWAT_STAGE_MAP["MV301"] == SWaTProcessStage.P3
        # Stage 4
        assert SWAT_STAGE_MAP["AIT401"] == SWaTProcessStage.P4
        assert SWAT_STAGE_MAP["UV401"] == SWaTProcessStage.P4
        # Stage 5
        assert SWAT_STAGE_MAP["PIT501"] == SWaTProcessStage.P5
        assert SWAT_STAGE_MAP["MV501"] == SWaTProcessStage.P5
        # Stage 6
        assert SWAT_STAGE_MAP["LIT601"] == SWaTProcessStage.P6
        assert SWAT_STAGE_MAP["P601"] == SWaTProcessStage.P6

    def test_actuators_mapped_to_digital_state(self):
        for tag in ["MV101", "P101", "P201", "MV301", "P401", "UV401", "P501", "MV501", "P601"]:
            info = parse_swat_tag(tag)
            assert info.tag_type == SWaTTagType.ACTUATOR
            assert info.modality == Modality.DIGITAL_STATE

    def test_pressure_sensors_mapped_to_pressure(self):
        for tag in ["DPIT301", "PIT501", "PIT502", "PIT503"]:
            info = parse_swat_tag(tag)
            assert info.tag_type == SWaTTagType.SENSOR
            assert info.modality == Modality.PRESSURE

    def test_other_sensors_mapped_to_unknown_modality(self):
        # FLOW (FIT), LEVEL (LIT), and CHEMICAL (AIT) must not invent physical ranges
        # or assign unsupported modalities. Modality.UNKNOWN correctly maps to standard
        # continuous statistical features (mean, std) in FeatureExtractor.
        for tag in ["FIT101", "LIT101", "AIT201", "FIT301", "LIT401", "AIT501", "FIT601"]:
            info = parse_swat_tag(tag)
            assert info.tag_type == SWaTTagType.SENSOR
            assert info.modality == Modality.UNKNOWN

    def test_dynamic_parsing_and_unrecognized_tags(self):
        # Dynamic inference for a plausible custom tag
        info = parse_swat_tag("FIT202")
        assert info.tag_type == SWaTTagType.SENSOR
        assert info.stage == SWaTProcessStage.P2
        assert info.modality == Modality.UNKNOWN

        # Completely unrecognizable tag
        unknown_info = parse_swat_tag("XYZ999")
        assert unknown_info.tag_type == SWaTTagType.UNKNOWN
        assert unknown_info.stage is None
        assert unknown_info.modality == Modality.UNKNOWN


